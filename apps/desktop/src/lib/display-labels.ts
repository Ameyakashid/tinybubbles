/**
 * Plain-language display overrides (see DESIGN.md — simplify pass).
 *
 * The translated strings live in packages/core (edit-forbidden) and speak GTD:
 * "Next Actions", "Someday/Maybe", "Waiting For". The shell shows plainer
 * words a child could hear read aloud. This map is the single place where
 * display text is overridden — core is untouched, and the override only
 * applies at call sites that opt in via displayLabel().
 *
 * Per-locale tables: each language carries its own kid-register words —
 * the word a parent would actually say to a young child in that language,
 * not a dictionary rendering of the English kid-word (so fr "Vide ton sac"
 * for the mind sweep, ja おかたづけ for tidying, zh 以后再说 for
 * "maybe later"). Rules:
 *
 * - A key missing from a locale's table falls back to the core translation
 *   for that locale, exactly as before. Keys are deliberately omitted where
 *   the core word is already fine for a child or where the English kid-word
 *   has no safe short equivalent (e.g. Russian numeral grammar cannot share
 *   one label between a section title and a "{count} {label}" line).
 * - Locales with no table at all (ar, cs, fa, hi, vi) stay on their core
 *   translations: a wrong-register guess is worse than the adult word, and
 *   those need a native check (recorded in DESIGN.md).
 * - Japanese overrides are written kana-first on purpose — the reader is a
 *   young child, unlike core's kanji-register strings.
 * - Every key used here must exist in the English table below; the English
 *   table is the contract for which surfaces the shell re-words
 *   (display-labels.test.ts pins this).
 */
