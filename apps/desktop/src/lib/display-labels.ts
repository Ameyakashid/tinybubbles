/**
 * The English override table, exported for the contract test: every locale's
 * keys must be a subset of these, so a typo'd key cannot silently become a
 * dead entry.
 */
export const DISPLAY_LABEL_KEY_CONTRACT = EN_OVERRIDES;

/** Locale tables, exported for the contract test only. */
export const DISPLAY_LABEL_TABLES = DISPLAY_LABEL_OVERRIDES_BY_LANGUAGE;

/** The translated label for `key`, unless the shell overrides it with plainer words. */
export function displayLabel(t: TranslateFn, language: Language, key: string, fallback: string): string {
    return DISPLAY_LABEL_OVERRIDES_BY_LANGUAGE[language]?.[key] ?? tFallback(t, key, fallback);
}
